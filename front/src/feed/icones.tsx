export function Icone({ nome, cheio }: { nome: keyof typeof OFICIAIS; cheio?: boolean }) {
  return <span className={cheio ? 'icone cheio' : 'icone'} aria-hidden="true" dangerouslySetInnerHTML={{ __html: OFICIAIS[nome] }} />;
}

